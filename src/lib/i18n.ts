export function formatRelativeTime(ts: unknown, lang: LanguageCode = 'en'): string {
  if (!ts) return lang === 'bn' ? 'এইমাত্র' : 'Just now';
  let date: Date;
  if (typeof ts === 'object' && ts !== null && 'toDate' in ts && typeof (ts as { toDate: () => Date }).toDate === 'function') {
    date = (ts as { toDate: () => Date }).toDate();
  } else if (ts instanceof Date) {
    date = ts;
  } else {
    date = new Date(String(ts));
  }
  const diffSec = Math.max(0, Math.floor((Date.now() - date.getTime()) / 1000));
  if (diffSec < 60) return lang === 'bn' ? 'এইমাত্র' : 'Just now';
  const diffMin = Math.floor(diffSec / 60);
  if (diffMin < 60) return lang === 'bn' ? `${diffMin} মি.` : `${diffMin}m`;
  const diffHr = Math.floor(diffMin / 60);
  if (diffHr < 24) return lang === 'bn' ? `${diffHr} ঘ.` : `${diffHr}h`;
  const diffDay = Math.floor(diffHr / 24);
  if (diffDay < 7) return lang === 'bn' ? `${diffDay} দি.` : `${diffDay}d`;
  return date.toLocaleDateString(lang === 'bn' ? 'bn-BD' : 'en-US', { month: 'short', day: 'numeric' });
}
